test('activates through captured mail, signs in and rejects arbitrary return destinations',async({page})=>{
  await page.goto('/account/register?next=%2Fbook')
  await page.getByLabel('Your name',{exact:true}).fill('Customer browser fixture')
  await page.getByLabel('Email address',{exact:true}).fill('new@example.test')
  await page.getByRole('button',{name:'Create account',exact:true}).click()
  await expect(page.locator('main').getByRole('status')).toContainText('If this address is eligible')
  const message=await mail('verify')
  await page.goto('/account/activate#token='+message.token)
  await page.getByLabel('Your name',{exact:true}).fill('Activated browser fixture')
  await page.getByLabel('New password',{exact:true}).fill(password)
  await page.getByLabel('Confirm password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Activate account',exact:true}).click()
  await expect(page.locator('main').getByRole('status')).toContainText('Your account is ready')
  expect(new URL(page.url()).hash).toBe('')
  await page.goto('/account/login?next=https%3A%2F%2Foutside.example')
  await page.getByLabel('Email address',{exact:true}).fill('new@example.test')
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page).toHaveURL(/\/account$/)
  const identity=await (await page.request.get('/api/identity/me',{headers:{origin}})).json()
  expect(identity.principal.kind).toBe('customer')
  expect((await page.request.post('/api/customers/login',{headers:{origin},data:{email:'new@example.test',password}})).ok()).toBe(false)
  await page.getByRole('button',{name:'Sign out',exact:true}).click()
  await expect(page).toHaveURL(origin+'/')
  expect((await (await page.request.get('/api/identity/me',{headers:{origin}})).json()).principal.kind).toBe('anonymous')
})
test('resets from captured mail and revokes a previously active browser session',async({page,browser})=>{
  await h.seed('customers',{name:'Recovery fixture',email:'recover@example.test',password,_verified:true})
  const signIn=await page.request.post('/api/identity/customer/login',{headers:{origin},data:{email:'recover@example.test',password}})
  expect(signIn.ok()).toBe(true)
  expect((await (await page.request.get('/api/identity/me',{headers:{origin}})).json()).principal.kind).toBe('customer')
  const recovery=await browser.newContext({baseURL:origin})
  try{
    const tab=await recovery.newPage()
    await tab.goto('/account/recover')
    await tab.getByLabel('Email address',{exact:true}).fill('recover@example.test')
    await tab.getByRole('button',{name:'Send recovery link',exact:true}).click()
    await expect(tab.locator('main').getByRole('status')).toContainText('If this address is eligible')
    const message=await mail('reset')
    await tab.goto('/account/reset#token='+message.token)
    await tab.getByLabel('New password',{exact:true}).fill('Replacement-browser-passphrase-258!')
    await tab.getByLabel('Confirm password',{exact:true}).fill('Replacement-browser-passphrase-258!')
    await tab.getByRole('button',{name:'Update password',exact:true}).click()
    await expect(tab.locator('main').getByRole('status')).toContainText('Your password has been updated')
    expect((await (await page.request.get('/api/identity/me',{headers:{origin}})).json()).principal.kind).toBe('anonymous')
    expect((await page.request.post('/api/identity/customer/login',{headers:{origin},data:{email:'recover@example.test',password}})).ok()).toBe(false)
    expect((await page.request.post('/api/identity/customer/login',{headers:{origin},data:{email:'recover@example.test',password:'Replacement-browser-passphrase-258!'}})).ok()).toBe(true)
  }finally{await recovery.close()}
})

test('preserves a guest selection after successful login and shares it with a second tab',async({page})=>{
  const account=await h.seed('customers',{name:'Handoff fixture',email:'handoff@example.test',password,_verified:true})
  await page.goto('/book?arrival=2027-06-10&departure=2027-06-12&adults=2&children=0')
  await page.getByLabel('Your name',{exact:true}).fill('Preserved fixture')
  await page.getByLabel('Email address',{exact:true}).fill(account.email)
  await page.getByRole('button',{name:'Sign in and keep my details'}).click()
  await expect(page).toHaveURL(/\/account\/login\?next=%2Fbook/)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page).toHaveURL(/\/book$/)
  await expect(page.getByLabel('Your name',{exact:true})).toHaveValue('Preserved fixture')
  await expect(page.getByRole('button',{name:'Continue with your account'})).toBeVisible()
  const second=await page.context().newPage()
  await second.goto('/book')
  await expect(second.getByLabel('Your name',{exact:true})).toHaveValue('Preserved fixture')
  expect((await h.rows('checkout-drafts'))[0].ownerCustomerId).toBe(account.id)
  await second.request.post('/api/identity/customer/logout',{headers:{origin}})
  await page.reload()
  await expect(page.getByLabel('Your name',{exact:true})).toHaveCount(0)
})
