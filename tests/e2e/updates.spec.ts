import '../support/env'
import {test,expect} from '@playwright/test'
import {createHarness,type TestHarness} from '../support/harness'
const origin='http://127.0.0.1:3043',password='Synthetic-editor-passphrase-982!'
let h:TestHarness
test.beforeAll(async()=>{h=await createHarness()})
test.beforeEach(async()=>{await h.reset()})
test.afterAll(async()=>{await h?.reset();await h?.close()})
test('publishes from a separate editor session and withdraws public detail immediately',async({page,browser})=>{
  await h.seed('staff-users',{name:'Editor fixture',email:'editor@example.test',password,role:'staff'})
  const editor=await browser.newContext({baseURL:origin})
  try{
    expect((await editor.request.post('/api/staff-users/login',{headers:{origin},data:{email:'editor@example.test',password}})).ok()).toBe(true)
    const draft=await editor.request.post('/api/posts?draft=true',{headers:{origin},data:{title:'A private editorial fixture',slug:'editorial-fixture',type:'story',summary:'A full summary.',body:'First paragraph.\n\nA second paragraph for full reading.',_status:'draft'}})
    expect(draft.ok()).toBe(true)
    const id=(await draft.json()).doc.id
    await page.goto('/updates')
    await expect(page.getByRole('heading',{name:'A private editorial fixture'})).toHaveCount(0)
    expect((await page.request.get(`/api/posts/${id}?draft=true`)).ok()).toBe(false)
    const preview=await editor.newPage()
    await preview.goto(`/updates/preview/${id}`)
    await expect(preview.getByRole('heading',{name:'A private editorial fixture',level:1})).toBeVisible()
    expect((await page.request.get(`/updates/preview/${id}`)).status()).toBe(404)
    const publish=await editor.request.patch(`/api/posts/${id}`,{headers:{origin},data:{_status:'published'}})
    expect(publish.ok()).toBe(true)
    await page.reload()
    await page.getByRole('link',{name:'Read A private editorial fixture'}).click()
    await expect(page).toHaveURL(/\/updates\/editorial-fixture$/)
    await expect(page.getByText('A second paragraph for full reading.',{exact:false})).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading',{name:'A private editorial fixture',level:1})).toBeVisible()
    expect((await editor.request.patch(`/api/posts/${id}`,{headers:{origin},data:{_status:'draft'}})).ok()).toBe(true)
    expect((await page.goto('/updates/editorial-fixture'))?.status()).toBe(404)
    expect(await h.rows('bookings')).toHaveLength(0)
    expect(await h.rows('payment-attempts')).toHaveLength(0)
  }finally{await editor.close()}
})
test('filters stories and upcoming events, then saves a contextual enquiry without booking',async({page})=>{
  const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Manila'}).format(new Date())
  await h.seed('posts',{title:'Story fixture',slug:'story-fixture',type:'story',summary:'Story summary.',body:'The full story.',_status:'published'})
  await h.seed('posts',{title:'Event fixture',slug:'event-fixture',type:'event',eventDate:today,summary:'Event summary.',body:'The full event details.',_status:'published'})
  await h.seed('posts',{title:'Past fixture',slug:'past-fixture',type:'event',eventDate:'2020-01-01',summary:'Past summary.',body:'Past event details.',_status:'published'})
  await page.goto('/updates')
  await page.getByRole('link',{name:'Stories',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Story fixture'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Event fixture'})).toHaveCount(0)
  await page.getByRole('link',{name:'Upcoming',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Event fixture'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Past fixture'})).toHaveCount(0)
  await page.getByRole('link',{name:'Read Event fixture'}).click()
  await expect(page).toHaveURL(/\/updates\/event-fixture$/)
  await page.getByLabel('Your name',{exact:true}).fill('Synthetic visitor')
  await page.getByLabel('Email address',{exact:true}).fill('visitor@example.test')
  await page.getByLabel('Your message',{exact:true}).fill('Synthetic contextual enquiry for this event.')
  await page.getByLabel('I agree to the privacy notice').check()
  await page.getByRole('button',{name:'Send enquiry'}).click()
  await expect(page.getByRole('status')).toContainText('Your enquiry has been received')
  const records=await h.rows('enquiries')
  expect(records).toHaveLength(1)
  expect(records[0].postSnapshot).toMatchObject({title:'Event fixture',eventDate:today})
  expect(await h.rows('allocations')).toHaveLength(0)
  expect(await h.rows('payment-transactions')).toHaveLength(0)
})
