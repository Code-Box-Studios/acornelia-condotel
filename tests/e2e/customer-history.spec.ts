import '../support/env'
import {test,expect} from '@playwright/test'
import {createHarness,type TestHarness} from '../support/harness'
let h:TestHarness
const origin='http://127.0.0.1:3043',password='Synthetic-history-browser-passphrase-382!'
test.beforeAll(async()=>{h=await createHarness()})
test.beforeEach(async()=>{await h.reset()})
test.afterAll(async()=>{await h?.reset();await h?.close()})
test('shows private booking history and detail without exposing another customer or relationship',async({page},testInfo)=>{
  const account=await h.seed('customers',{name:'History browser fixture',email:'history@example.test',password,_verified:true})
  const other=await h.seed('customers',{name:'Other fixture',email:'other@example.test',password,_verified:true})
  const base={status:'confirmed' as const,revision:1,arrival:'2027-05-10T00:00:00Z',departure:'2027-05-12T00:00:00Z',acceptedQuote:{total:{minor:'123456',currency:'PHP'}},contact:{name:'Different contact',email:'contact@example.test'},stayingGuest:'Separate guest',source:'website' as const}
  const own=await h.seed('bookings',{...base,code:'OWN-HISTORY-FIXTURE',ownerCustomer:account.id})
  const foreign=await h.seed('bookings',{...base,code:'PRIVATE-OTHER-FIXTURE',ownerCustomer:other.id})
  expect((await page.request.post('/api/identity/customer/login',{headers:{origin},data:{email:account.email,password}})).ok()).toBe(true)
  await page.goto('/account');await page.getByRole('link',{name:'My bookings',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Your stays, together.',exact:true})).toBeVisible()
  await expect(page.getByRole('link',{name:'View booking OWN-HISTORY-FIXTURE',exact:true})).toBeVisible()
  await expect(page.locator('main')).not.toContainText(foreign.code!)
  await page.getByRole('link',{name:'View booking OWN-HISTORY-FIXTURE',exact:true}).click()
  // The list also shows the code heading and total, so wait for the detail route; next dev may compile it first.
  await page.waitForURL('**/account/bookings/'+own.id)
  await expect(page.getByRole('heading',{name:'OWN-HISTORY-FIXTURE',exact:true})).toBeVisible()
  await expect(page.locator('main')).toContainText('₱1,234.56')
  await expect(page.locator('main')).toContainText('Different contact')
  await expect(page.locator('main')).toContainText('Separate guest')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:'.local/customer-booking-'+testInfo.project.name+'-light.png',fullPage:true})
  await page.getByRole('button',{name:'Switch color theme'}).click()
  await page.screenshot({path:'.local/customer-booking-'+testInfo.project.name+'-dark.png',fullPage:true})
  const api=await page.request.get('/api/customer/bookings',{headers:{origin}})
  expect(api.headers()['cache-control']).toContain('no-store')
  expect((await api.json()).items.map((item:{id:string})=>item.id)).toEqual([own.id])
  expect((await page.request.get('/api/customer/bookings?ownerCustomer='+other.id,{headers:{origin}})).status()).toBe(400)
  expect((await page.request.get('/api/bookings?depth=5',{headers:{origin}})).ok()).toBe(false)
  expect((await page.request.get('/api/payment-attempts?depth=5',{headers:{origin}})).ok()).toBe(false)
  const privatePage=await page.goto('/account/bookings/'+foreign.id)
  expect(privatePage?.status()).toBe(404)
  await expect(page.locator('main')).not.toContainText(foreign.code!)
  await page.goto('/account/bookings');await page.getByRole('button',{name:'Sign out',exact:true}).click();await expect(page).toHaveURL(origin+'/')
  expect((await page.request.get('/api/customer/bookings',{headers:{origin}})).status()).toBe(401)
  await page.goto('/account/bookings');await expect(page).toHaveURL(/\/account\/login/)
})
test('explains empty history and pending historical claims, in both themes and a narrow viewport',async({page})=>{
  const account=await h.seed('customers',{name:'Empty history fixture',email:'empty@example.test',password,_verified:true})
  expect((await page.request.post('/api/identity/customer/login',{headers:{origin},data:{email:account.email,password}})).ok()).toBe(true)
  await page.goto('/account/bookings')
  await expect(page.getByRole('heading',{name:'No bookings yet.',exact:true})).toBeVisible()
  await expect(page.locator('main')).toContainText('Earlier guest bookings need a separate ownership review.')
  await expect(page.getByRole('link',{name:'Plan a stay',exact:true})).toBeVisible()
  await page.setViewportSize({width:320,height:780})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.getByRole('button',{name:'Switch color theme'}).click()
  await expect(page.getByRole('heading',{name:'No bookings yet.',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
